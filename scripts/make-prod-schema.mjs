// Generate prisma/schema.prod.prisma from the dev schema by swapping the
// datasource to PostgreSQL and adding the binary target Netlify's runtime needs.
// This keeps schema.prisma on SQLite (so local dev + tests stay zero-setup and
// green) while production builds against Postgres — with zero schema drift.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const src = resolve(process.cwd(), "prisma/schema.prisma");
const out = resolve(process.cwd(), "prisma/schema.prod.prisma");

let schema = readFileSync(src, "utf8");

// 1. datasource provider: sqlite -> postgresql
schema = schema.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');

// 2. add binaryTargets so the client works on Netlify's Lambda runtime
if (!/binaryTargets/.test(schema)) {
  schema = schema.replace(
    /generator\s+client\s*\{/,
    'generator client {\n  binaryTargets = ["native", "rhel-openssl-3.0.x"]'
  );
}

const banner = "// AUTO-GENERATED by scripts/make-prod-schema.mjs — do not edit.\n// Source of truth is prisma/schema.prisma. Regenerated on every prod build.\n\n";
writeFileSync(out, banner + schema, "utf8");
console.log("✓ Wrote prisma/schema.prod.prisma (PostgreSQL + Netlify engine).");
